// Draws text in the tracing alphabet. size = cap height in points. style: solid | dots | dashed.
function drawStrokes(p, text, x, base, size, o = {}) {
  const k = size / 10, sw = o.sw || Math.max(1.4, size * 0.075), gap = (o.gap || 1.4) * k;
  let pen = x;
  for (const ch of String(text)) {
    if (ch === " ") { pen += 3.6 * k; continue; }
    const g = G[ch]; if (!g) { pen += 4 * k; continue; }
    g.s.forEach((pts, si) => {
      const d = "M" + pts.map(([px, py]) => (pen + px * k).toFixed(2) + " " + (base - py * k).toFixed(2)).join(" L");
      const style = o.style || "solid";
      p.path(d, { stroke: o.color || "#2B2B35", sw, cap: "round", join: "round", dash: style === "dots" ? `0 ${(sw * 1.9).toFixed(2)}` : style === "dashed" ? `${(sw * 1.6).toFixed(1)} ${(sw * 1.6).toFixed(1)}` : null });
      if (o.start && si === 0) p.circle(pen + pts[0][0] * k, base - pts[0][1] * k, sw * 1.15, { fill: o.start });
    });
    (g.dots || []).forEach(([dx, dy]) => p.circle(pen + dx * k, base - dy * k, sw * 0.75, { fill: o.color || "#2B2B35" }));
    pen += (g.w + gap / k) * k;
  }
  return pen - x;
}
function strokeWidth(text, size, gap) { const k = size / 10; let w = 0; for (const ch of String(text)) w += ch === " " ? 3.6 * k : ((G[ch] ? G[ch].w : 4) * k + (gap || 1.4) * k); return w; }
module.exports = { drawStrokes, strokeWidth, G };
