// A simple "ball and stick" print alphabet for tracing worksheets.
// Units: baseline y=0, x-height 5, cap height 10, descenders to -4.5. y points up.
const D = Math.PI / 180;
function arc(cx, cy, rx, ry, a0, a1, n) {
  n = n || Math.max(8, Math.round(Math.abs(a1 - a0) / 12));
  const pts = []; for (let i = 0; i <= n; i++) { const a = (a0 + (a1 - a0) * i / n) * D; pts.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a)]); }
  return pts;
}
